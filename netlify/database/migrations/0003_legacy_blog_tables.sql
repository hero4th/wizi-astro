-- Tablas legacy del blog original (esquema MySQL portado a Postgres), agregadas
-- por el cambio del amigo. Idempotente: en la DB de produccion ya existen.
-- La app Astro NO las usa (usa `posts`); se conservan como fuente/feature legacy.

CREATE TABLE IF NOT EXISTS autores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100),
  titulo varchar(45),
  foto varchar(255),
  bio text,
  credenciales text,
  fecha_actualizacion integer
);

CREATE TABLE IF NOT EXISTS blog (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(255) NOT NULL,
  post text NOT NULL,
  indice text,
  previo text NOT NULL,
  imagen varchar(300) NOT NULL,
  alt_imagen varchar(200),
  active boolean NOT NULL DEFAULT false,
  fecha bigint NOT NULL,
  url_personalizada varchar(190) NOT NULL UNIQUE,
  sni_titulo varchar(255) NOT NULL DEFAULT '',
  sni_descripcion varchar(320) NOT NULL DEFAULT '',
  sni_palabrasclaves varchar(500) NOT NULL DEFAULT '',
  autor integer NOT NULL DEFAULT 0,
  veces_visto integer NOT NULL DEFAULT 0,
  tiempo_lectura integer,
  last_change bigint NOT NULL,
  last_change_admin integer NOT NULL DEFAULT 0,
  categoria jsonb,
  fecha_original bigint
);

CREATE INDEX IF NOT EXISTS idx_blog_fecha ON blog (fecha);
CREATE INDEX IF NOT EXISTS idx_blog_active_fecha ON blog (active, fecha);
CREATE INDEX IF NOT EXISTS idx_blog_autor ON blog (autor);

